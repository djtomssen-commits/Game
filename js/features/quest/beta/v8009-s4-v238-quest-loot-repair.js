/* ===== V4.02 Quest loot repair =====
   V4.02 still calls makeItem(), but that helper no longer exists.
   Its try/catch silently swallowed the resulting ReferenceError, so the
   item roll could succeed while no item was actually awarded.
*/

/* Compatibility helper used by the active V4.02 quest payout.
   Keeps the original quest design:
   - 75% class-appropriate item
   - 25% item from another class
   - rarity is generated by the existing class-loot system.
*/
function makeItem(){
  const own=s.playerClass||'grower';

  if(Math.random()<.75){
    return makeClassLoot(own,'normal');
  }

  const others=['grower','bruiser','scout','frost','summoner'].filter(x=>x!==own);
  const cls=others[Math.floor(Math.random()*others.length)]||own;
  return makeClassLoot(cls,'normal');
}


/* The original base quest code also had a rare SET roll inside an item drop,
   but V4.02 replaced that section. Restore it around the final claim path
   without paying duplicate normal items.
*/
const v238BaseClaimQuest=claimQuest;

claimQuest=function(...args){
  const q=s.quests?.active;
  const ready=!!q && Date.now()>=Number(q.ends||0);

  if(!ready){
    return v238BaseClaimQuest.apply(this,args);
  }

  const beforeInventory=Array.isArray(s.inventory)?s.inventory.length:0;
  const result=v238BaseClaimQuest.apply(this,args);

  /*
    If V4.02 awarded a normal item through the repaired makeItem(), leave it.
    SET items remain a separate very rare quest jackpot, matching the old
    intended conditional 1.5% roll inside an item reward.
  */
  const afterInventory=Array.isArray(s.inventory)?s.inventory.length:0;
  const gotNormalItem=afterInventory>beforeInventory;

  if(gotNormalItem && Math.random()<.015){
    try{
      /*
        Upgrade the newest quest item to a genuine class SET piece rather
        than adding a second item for the same reward roll.
      */
      const slot=setBases[Math.floor(Math.random()*setBases.length)].slot;
      const setItem=makeSetItem(s.playerClass||'grower',slot);
      s.inventory[s.inventory.length-1]=setItem;
      try{persist(false)}catch(e){}
    }catch(e){
      console.error('V4.02 quest set item roll',e);
    }
  }

  return result;
};


/* Keep all dungeon-key representations synchronized.
   V4.02 already handles Dungeon 2. This repairs later quest-found stones,
   whose V4.02 code still writes only s.dungeon.keys[index].
*/
function v238SyncQuestDungeonKeys(){
  if(!s.dungeon)return;

  s.dungeon.unlocked=Array.isArray(s.dungeon.unlocked)
    ?s.dungeon.unlocked.map(Number)
    :[];

  const keys=(s.dungeon.keys&&typeof s.dungeon.keys==='object')
    ?s.dungeon.keys
    :{};

  Object.entries(keys).forEach(([raw,has])=>{
    if(!has)return;
    const i=Number(raw);
    if(
      Number.isInteger(i) &&
      i>0 &&
      i<dungeons.length &&
      !s.dungeon.unlocked.includes(i)
    ){
      s.dungeon.unlocked.push(i);
    }
  });
}


/* Wrap once more so a later-dungeon key found by the old quest code becomes
   usable immediately by the current 20-dungeon map.
*/
const v238LootClaimQuest=claimQuest;
claimQuest=function(...args){
  const result=v238LootClaimQuest.apply(this,args);
  v238SyncQuestDungeonKeys();
  return result;
};

